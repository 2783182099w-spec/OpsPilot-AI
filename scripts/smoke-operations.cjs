// Requires temporary local fixtures; never executes a task or opens SSH/SFTP.
const {chromium}=require(process.env.OPSPILOT_PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs'),os=require('os'),path=require('path');
(async()=>{
  const fixture=JSON.parse(fs.readFileSync(process.env.OPSPILOT_SMOKE_FIXTURE||path.join(os.tmpdir(),'opspilot-ops-smoke-auth.json'),'utf8'));
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const context=await browser.newContext({viewport:{width:1600,height:1000}});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.routeWebSocket('**/ws/**',socket=>socket.close());
  await page.route('**/host/*/files**',route=>{
    if(route.request().url().includes('history=1'))return route.continue();
    errors.push('Unexpected SFTP connection attempt');return route.abort();
  });
  try{
    await page.goto('http://127.0.0.1:9000/login',{waitUntil:'networkidle'});
    const login=await context.request.post('http://127.0.0.1:8000/users/login/',{data:{username:fixture.username,password:fixture.password}});
    if(!login.ok())throw new Error('Login failed');
    const token=(await login.json()).access;
    await page.evaluate(token=>sessionStorage.setItem('opspilot-ai',JSON.stringify({token,remember:false})),token);
    await context.setExtraHTTPHeaders({Authorization:'jwt '+token});
    await page.goto('http://127.0.0.1:9000/opspilot/host',{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'详情',exact:true}).click();
    await page.getByText('资产详情与变更记录',{exact:true}).waitFor();
    await page.locator('.ant-modal:visible .ant-modal-close').click();
    await page.getByRole('button',{name:'文件',exact:true}).click();
    await page.getByText('SFTP 文件传输',{exact:true}).waitFor();
    await page.locator('.ant-modal:visible .ant-modal-close').click();
    await page.goto('http://127.0.0.1:9000/opspilot/operations',{waitUntil:'networkidle'});
    await page.locator('.ant-table-tbody tr input[type=checkbox]').first().check();
    await page.getByRole('tab',{name:'定时检查'}).click();
    const planName=fixture.username+'_'+Date.now();
    await page.getByRole('button',{name:'新建计划',exact:true}).click();
    await page.getByPlaceholder('例如：保障期间每日健康检查').fill(planName);
    const dialog=page.locator('.ant-modal:visible');
    await dialog.locator('.ant-select').first().click();
    await page.locator('.ant-select-item-option').filter({hasText:fixture.username}).first().click();
    await dialog.getByText('计划名称',{exact:true}).click();
    await dialog.getByRole('button',{name:/确.*定|OK/}).click();
    await page.getByRole('cell',{name:planName,exact:true}).waitFor();
    await page.locator('tr').filter({hasText:planName}).getByRole('button',{name:/^编\s*辑$/}).click();
    await page.getByPlaceholder('例如：保障期间每日健康检查').fill(planName+'-edited');
    await page.locator('.ant-modal:visible').getByRole('button',{name:/确.*定|OK/}).click();
    await page.getByRole('cell',{name:planName+'-edited',exact:true}).waitFor();
    const plans=await context.request.get('http://127.0.0.1:8000/mtask/schedules');
    if(!(await plans.json()).every(x=>!x.enabled))throw new Error('Schedule unexpectedly enabled');
    await page.getByRole('tab',{name:'命令模板'}).click();
    await page.locator('tr').filter({hasText:fixture.username}).getByRole('button',{name:'使用模板'}).click();
    await page.getByText('使用模板：'+fixture.username,{exact:true}).waitFor();
    await page.locator('.ant-modal:visible .ant-select').last().click();
    await page.locator('.ant-select-item-option').filter({hasText:'sshd'}).click();
    await page.getByRole('button',{name:'预览最终命令',exact:true}).click();
    await page.locator('.ant-modal:visible pre').filter({hasText:'systemctl status sshd'}).waitFor();
    await page.locator('.ant-modal:visible .ant-modal-close').click();
    await page.goto('http://127.0.0.1:9000/opspilot/alerts',{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'证据与处理'}).click();
    await page.getByText('告警证据与处理',{exact:true}).waitFor();
    await page.locator('.ant-drawer-content:visible .ant-drawer-close').click();
    await page.goto('http://127.0.0.1:9000/opspilot/monitoring',{waitUntil:'networkidle'});
    await page.getByRole('tab',{name:'主机监控',exact:true}).waitFor();
    await page.locator('tr').filter({hasText:fixture.username}).getByText(fixture.username,{exact:true}).click();
    await page.getByRole('tab',{name:'指标趋势',exact:true}).waitFor();
    await page.getByText('该主机尚未启用持续监控',{exact:false}).waitFor();
    const task=await context.request.post('http://127.0.0.1:8000/mtask/tasks',{data:{host_ids:[fixture.host_id],cmd:'id',confirmed:true}});
    const taskData=await task.json();
    if(taskData.status!=='awaiting_approval')throw new Error('Command should not execute');
    await context.request.post(`http://127.0.0.1:8000/mtask/tasks/${taskData.id}/action`,{data:{action:'cancel'}});
    await page.goto('http://127.0.0.1:9000/opspilot/tasks',{waitUntil:'networkidle'});
    await page.getByText('已取消',{exact:true}).first().waitFor();
    await page.getByRole('button',{name:/^结\s*果$/}).first().click();
    await page.locator('.ant-modal:visible').getByText('主机进度',{exact:true}).waitFor();
    await page.locator('.ant-modal:visible .ant-modal-close').click();
    await page.goto(`http://127.0.0.1:9000/opspilot/tasks?kind=inspection&task=${fixture.inspection_id}`,{waitUntil:'networkidle'});
    await page.locator('.ant-modal:visible').getByText('异常 1 项',{exact:true}).waitFor();
    await page.locator('.ant-modal:visible').getByText('fixture high usage',{exact:true}).waitFor();
    const report=await context.request.get(`http://127.0.0.1:8000/mtask/tasks/${fixture.inspection_id}/health-report`);
    if(!report.ok()||!(await report.text()).includes('fixture high usage'))throw new Error('Health report export failed');
    await page.locator('.ant-modal:visible .ant-modal-close').click();
    await page.getByRole('tab',{name:'SSH 会话与文本回放',exact:true}).click();
    await page.getByRole('button',{name:'文本回放',exact:true}).click();
    await page.locator('.terminal-text').filter({hasText:'offline text fixture'}).waitFor();
    await page.getByRole('button',{name:'回到开头',exact:true}).click();
    if(await page.locator('.terminal-text').innerText())throw new Error('Replay did not reset');
    await page.getByRole('button',{name:'逐行播放',exact:true}).click();
    await page.locator('.terminal-text').filter({hasText:'whoami'}).waitFor();
    await page.locator('.ant-modal:visible .ant-modal-close').click();
    await page.goto('http://127.0.0.1:9000/opspilot/show_center',{waitUntil:'networkidle'});
    await page.getByRole('heading',{name:'运维态势总览',exact:true}).waitFor();
    await page.getByRole('button',{name:'全屏大屏',exact:true}).click();
    await page.locator('.wall-full').waitFor();
    fs.mkdirSync(path.join(__dirname,'../.runtime'),{recursive:true});
    await page.locator('.wall').screenshot({path:path.join(__dirname,'../.runtime/qa-dashboard.png')});
    await page.getByRole('button',{name:'退出大屏',exact:true}).click();
    for(const language of ['shell','python']){
      await page.goto('http://127.0.0.1:9000/opspilot/multi_exec',{waitUntil:'networkidle'});
      await page.getByRole('button',{name:'选择主机',exact:true}).click();
      await page.locator('.ant-modal:visible .ant-table-tbody input[type=checkbox]').first().check();
      await page.locator('.ant-modal:visible').getByRole('button',{name:/确.*定|OK/}).click();
      const source=language==='shell'?'printf "%s\\n" "$1"\n':'import sys\nprint(sys.argv[1])\n';
      const filename=language==='shell'?'test.sh':'test.py';
      await page.locator('input[type=file]').setInputFiles({name:filename,mimeType:'text/plain',buffer:Buffer.from(source)});
      await page.getByPlaceholder('例如：资源与服务状态汇总').fill(fixture.username+'-'+language);
      await page.getByRole('button',{name:'添加参数',exact:true}).click();
      await page.getByPlaceholder('参数 1',{exact:true}).fill('literal ; $(not-run)');
      await page.getByRole('button',{name:'预览脚本与执行计划',exact:true}).click();
      await page.getByText('3. 确认脚本执行计划',{exact:true}).waitFor();
      await page.locator('.ant-modal:visible').screenshot({path:path.join(__dirname,'../.runtime/qa-script-'+language+'.png')});
      await page.getByRole('button',{name:'确认并提交任务',exact:true}).click();
      await page.waitForURL('**/opspilot/tasks?task=*');
      const id=new URL(page.url()).searchParams.get('task');
      const response=await context.request.get(`http://127.0.0.1:8000/mtask/tasks/${id}`);
      const created=await response.json();
      if(created.kind!=='script'||created.status!=='awaiting_approval'||created.script_meta.sha256.length!==64)throw new Error('Script snapshot or approval failed');
      await context.request.post(`http://127.0.0.1:8000/mtask/tasks/${id}/action`,{data:{action:'cancel'}});
    }
    const adminLogin=await context.request.post('http://127.0.0.1:8000/users/login/',{data:{username:fixture.admin_username,password:fixture.password}});
    const adminToken=(await adminLogin.json()).access;
    await page.evaluate(token=>sessionStorage.setItem('opspilot-ai',JSON.stringify({token,remember:false})),adminToken);
    await context.setExtraHTTPHeaders({Authorization:'jwt '+adminToken});
    await page.goto('http://127.0.0.1:9000/opspilot/operations',{waitUntil:'networkidle'});
    await page.getByRole('tab',{name:'命令模板'}).click();
    await page.getByRole('button',{name:'用“服务状态查询”示例创建'}).click();
    const editor=page.locator('.ant-modal:visible');
    await editor.locator('input').first().fill(fixture.username+'-template');
    await editor.locator('.ant-select').first().click();
    await page.locator('.ant-select-item-option').filter({hasText:fixture.username}).first().click();
    await editor.getByText('名称',{exact:true}).click();
    await editor.getByRole('button',{name:/确.*定|OK/}).click();
    await page.getByRole('cell',{name:fixture.username+'-template',exact:true}).waitFor();
    await page.goto('http://127.0.0.1:9000/opspilot/multi_exec',{waitUntil:'networkidle'});
    await page.locator('input[type=file]').setInputFiles({name:'admin-test.py',mimeType:'text/plain',buffer:Buffer.from('print("local fixture only")\n')});
    await page.getByPlaceholder('例如：资源与服务状态汇总').fill(fixture.username+'-script-library');
    await page.getByRole('button',{name:'保存到脚本库',exact:true}).click();
    await page.getByText('脚本版本已保存，已提交任务不受影响',{exact:true}).waitFor();
    await page.getByPlaceholder('说明查询或修改什么').fill('offline version test');
    const [savedVersion] = await Promise.all([
      page.waitForResponse(r=>r.url().includes('/mtask/scripts/')&&r.request().method()==='PATCH'),
      page.getByRole('button',{name:'保存新版本',exact:true}).click(),
    ]);
    if(!savedVersion.ok())throw new Error('Script library update failed: HTTP '+savedVersion.status());
    const scripts=await context.request.get('http://127.0.0.1:8000/mtask/scripts');
    const saved=(await scripts.json()).find(s=>s.name===fixture.username+'-script-library');
    if(!saved||saved.version!==2)throw new Error('Script library version save failed');
    const monitorResponse=await context.request.get('http://127.0.0.1:8000/monitoring/overview');
    const realTargets=(await monitorResponse.json()).rows.filter(r=>r.target?.enabled);
    if(realTargets.length){
      await page.goto('http://127.0.0.1:9000/opspilot/monitoring',{waitUntil:'networkidle'});
      const row=page.locator('tr').filter({hasText:realTargets[0].name});
      await row.getByRole('button',{name:/趋\s*势/}).click();
      await page.locator('.ant-modal:visible canvas').waitFor();
      await page.locator('.ant-modal:visible .ant-modal-close').click();
    }
    await page.goto('http://127.0.0.1:9000/opspilot/show_center',{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'全屏大屏',exact:true}).click();
    await page.locator('.wall-full').waitFor();
    await page.locator('.wall').screenshot({path:path.join(__dirname,'../.runtime/qa-dashboard-live.png')});
    await page.getByRole('button',{name:'退出大屏',exact:true}).click();
    await page.setViewportSize({width:1366,height:768});
    await page.locator('.wall').screenshot({path:path.join(__dirname,'../.runtime/qa-dashboard-1366.png')});
    if(errors.length)throw new Error(errors.join('; '));
    console.log('PASS: script import/preview/approval for Shell and Python, script library revisions, dashboard and fullscreen, asset details, files without connection, independent schedule creation/edit, template preview and admin parameter form, unified alerts, monitoring, workbench, standalone health report, filtered inspection report, command record, text replay; no JavaScript errors.');
  }catch(error){
    console.error('Browser runtime errors:',JSON.stringify(errors));
    if(await page.locator('#webpack-dev-server-client-overlay').count()){
      console.error('Development overlay:',(await page.frameLocator('#webpack-dev-server-client-overlay').locator('body').innerText()).slice(0,2500));
    }
    throw error;
  }finally{await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1});
